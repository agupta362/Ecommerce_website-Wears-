export const getProductBySlug = (slug: string): Product | undefined => {
  return products.find(p => p.slug === slug);
};

export const getFeaturedProducts = (): Product[] => {
  return products.filter(p => p.isFeatured);
};

export const getNewArrivals = (): Product[] => {
  return products.filter(p => p.isNew);
};

export const getSaleProducts = (): Product[] => {
  return products.filter(p => p.isSale);
};

export const getProductsByCategory = (category: string): Product[] => {
  return products.filter(p => p.category === category);
};

export const getTotalStock = (sizeStock: { size: string; stock: number }[]): number => {
  return sizeStock.reduce((total, item) => total + item.stock, 0);
};

export const isLowStock = (sizeStock: { size: string; stock: number }[]): boolean => {
  return getTotalStock(sizeStock) < 10;
};
